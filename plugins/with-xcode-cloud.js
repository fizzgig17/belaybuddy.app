// Keeps Xcode Cloud's entry scripts in ios/ci_scripts/.
//
// Xcode Cloud only runs scripts from a ci_scripts folder next to the Xcode
// workspace, so ios/ci_scripts/ is committed. But `expo prebuild` recreates
// ios/ from scratch and would delete it, so this plugin writes the two small
// wrappers back on every prebuild. The real logic lives in
// scripts/xcode-cloud/, outside ios/, so prebuild never touches it.
const fs = require('fs');
const path = require('path');
const { withDangerousMod } = require('expo/config-plugins');

const WRAPPERS = {
  'ci_post_clone.sh': 'post-clone.sh',
  'ci_post_xcodebuild.sh': 'post-xcodebuild.sh',
};

const wrapper = (target) =>
  [
    '#!/bin/sh',
    '# Generated by plugins/with-xcode-cloud.js — edit scripts/xcode-cloud/ instead.',
    `exec "$CI_PRIMARY_REPOSITORY_PATH/scripts/xcode-cloud/${target}"`,
    '',
  ].join('\n');

module.exports = function withXcodeCloud(config) {
  return withDangerousMod(config, [
    'ios',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'ci_scripts');
      fs.mkdirSync(dir, { recursive: true });
      for (const [name, target] of Object.entries(WRAPPERS)) {
        const file = path.join(dir, name);
        fs.writeFileSync(file, wrapper(target));
        fs.chmodSync(file, 0o755);
      }
      return cfg;
    },
  ]);
};
